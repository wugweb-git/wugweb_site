#!/usr/bin/env node
/**
 * Compile the skill into every single-file export the Wugweb skill system
 * ships: AGENTS.md (the whole skill in one file), adapters/cursor/<name>.mdc,
 * adapters/chatgpt/instructions.md, agents/openai.yaml and export/<name>.md.
 * Edit the sources, never the output. `--check` fails on any stale file.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { SKILL_DIR, readRules, readSections } from './lib.mjs'

const check = process.argv.includes('--check')
const OUT_AGENTS = join(SKILL_DIR, 'AGENTS.md')
const OUT_CURSOR = join(SKILL_DIR, 'adapters/cursor/wugweb-kits.mdc')
const OUT_CHATGPT = join(SKILL_DIR, 'adapters/chatgpt/instructions.md')
const OUT_OPENAI = join(SKILL_DIR, 'agents/openai.yaml')
const OUT_EXPORT = join(SKILL_DIR, 'export/wugweb-kits.md')

const meta = JSON.parse(await readFile(join(SKILL_DIR, 'metadata.json'), 'utf8'))
const sections = await readSections()
const rules = await readRules()

const extra = async (f) => readFile(join(SKILL_DIR, f), 'utf8').catch(() => '')
const skillFile = await extra('SKILL.md')
const skillFrontmatter = /^---\n([\s\S]*?)\n---\n/.exec(skillFile)?.[1] ?? ''
const skillBody = skillFile.replace(/^---[\s\S]*?\n---\n/, '').trim()
const skillDescription = /^description:\s*['"]([\s\S]*?)['"]\s*$/m.exec(skillFrontmatter)?.[1] ?? ''
const shellRef = (await extra('references/layout-shell.md')).trim()
const standing = (await extra('references/standing-rules.md')).trim()

// 1. AGENTS.md: skill body + layout shell reference + standing rules + per-rule bodies
const agentsLines = [
  '<!-- Generated by scripts/build.mjs — do not edit by hand. -->',
  '',
  '# Wugweb Kits',
  '',
  `**Version ${meta.version}** · ${meta.organization} · ${meta.date}`,
  '',
  meta.abstract,
  '',
  '## Skill body', '', skillBody, '',
  '---', '', '## Layout shell reference', '', shellRef, '',
  '---', '', '## Standing rules (marked copy)', '', standing, '',
  '---', '',
  '## Contents', '',
]
for (const s of sections) {
  const rs = rules.filter((r) => r.section === s.id)
  agentsLines.push(`${s.order}. **${s.title}** (${s.impact}) — ${rs.length} rules`)
  for (const r of rs) agentsLines.push(`   - \`${r.id}\` — ${r.data.impactDescription ?? ''}`)
}
agentsLines.push('')
for (const s of sections) {
  agentsLines.push('---', '', `## ${s.order}. ${s.title}`, '', `**Impact:** ${s.impact}`, '', s.description, '')
  for (const r of rules.filter((x) => x.section === s.id)) {
    agentsLines.push(
      `### \`${r.id}\``,
      '',
      `**Impact:** ${r.data.impact} — ${r.data.impactDescription ?? ''}`,
      '',
      r.body.replace(/^##\s+.*$/m, '').trim(),
      '',
    )
  }
}
if (meta.references?.length) {
  agentsLines.push('---', '', '## References', '')
  for (const ref of meta.references) agentsLines.push(`- ${ref}`)
  agentsLines.push('')
}
const agentsOutput = agentsLines.join('\n')

// 2. Cursor rule: the description plus the SKILL.md body
const cursorOutput = [
  '---',
  `description: ${JSON.stringify(skillDescription)}`,
  'globs: ["**/*.astro", "**/*.css", "**/kits_design_system/**", "**/skills/wugweb-kits/**", "src/styles/**"]',
  'alwaysApply: false',
  '---',
  '',
  '<!-- Generated by scripts/build.mjs. Do not edit by hand. -->',
  '',
  skillBody,
  '',
].join('\n')

// 3. ChatGPT instructions: a fixed template that points at the uploaded AGENTS.md
const chatgptOutput = `<!-- Generated by scripts/build.mjs. Do not edit by hand. -->

# Instructions for a custom GPT or project

Paste the block below into the instructions field. Upload \`AGENTS.md\` from this skill as a knowledge file.

\`\`\`
You keep the Wugweb Kits design system in agreement with the code and the
design-system docs, using the method in the uploaded file AGENTS.md. Read
AGENTS.md before any task about tokens, the layout shell, sections, blocks,
components, block docs, motion or accessibility on the Wugweb site.

Always:
- Treat the three design docs as the source: tokens/layout-shell.md is
  binding, with tokens/sizing.md and components.md beside it. Code that
  disagrees with layout-shell.md is wrong, not the doc.
- Read a value from the doc, never from memory.
- Pick the phases the question needs: only an audit runs every phase.
- Give computed totals first, then one line per finding with its severity,
  its file and line, and its rule id.
- Compute every count. If a count could not be computed, say so.
- State what was not checked.
- Show every proposed change as current, then proposed. Never invent a
  finding.

Never:
- Edit a token, a doc, a component or a site file without the owner's yes.
- Reintroduce a retired shell value. The list is in AGENTS.md.
- Delete anything without asking.
- Write visible copy (ask wugweb-work), art direction (wugweb-brand-os),
  schema or search rules (wugweb-seo), or content plans (wugweb-strategy).
- Change stored data, a Sanity schema or a sync script (wugweb-engineer).
  Build, deploy and git follow the AGENTS.md at the repo root.
- Use em or en dashes in anything a visitor reads.

If you can run code, run scripts/kits-inventory.mjs for raw values and shell
faults, scripts/kits-check-page.mjs on rendered HTML for labelling, and
scripts/kits-doc-drift.mjs for doc-and-code drift. If you cannot, apply the
rules by reading the files the user shares and label the result a manual
check.
\`\`\`
`

// 4. OpenAI display settings
const openaiOutput = `# Generated by scripts/build.mjs. Do not edit by hand.
# Display settings for Codex and the ChatGPT desktop app. Other agents ignore this file.
interface:
  display_name: "Wugweb Kits"
  short_description: "Map, audit and spec the Wugweb Kits design system"
  default_prompt: "Audit this page against the Wugweb Kits layout shell and tell me what to fix."
policy:
  allow_implicit_invocation: true
`

// 5. Export: AGENTS.md prefaced with a three-line header
const exportOutput = `# wugweb-kits (single-file export, v${meta.version})

Built from the skill folder. Rebuild whenever the skill changes. Read the skill first, then the reference a part names.

${agentsOutput}`

const files = [
  { path: OUT_AGENTS, content: agentsOutput, label: 'AGENTS.md' },
  { path: OUT_CURSOR, content: cursorOutput, label: 'adapters/cursor/wugweb-kits.mdc' },
  { path: OUT_CHATGPT, content: chatgptOutput, label: 'adapters/chatgpt/instructions.md' },
  { path: OUT_OPENAI, content: openaiOutput, label: 'agents/openai.yaml' },
  { path: OUT_EXPORT, content: exportOutput, label: 'export/wugweb-kits.md' },
]

if (check) {
  let stale = 0
  for (const f of files) {
    const current = await readFile(f.path, 'utf8').catch(() => null)
    if (current !== f.content) { console.error(`${f.label} is stale. Run: node scripts/build.mjs`); stale++ }
  }
  if (stale) process.exit(1)
  console.log('AGENTS.md, cursor rule, chatgpt instructions, openai.yaml and export are up to date.')
} else {
  for (const f of files) await writeFile(f.path, f.content)
  console.log(`Wrote AGENTS.md, cursor rule, chatgpt instructions, openai.yaml, export — ${rules.length} rules, ${sections.length} sections.`)
}

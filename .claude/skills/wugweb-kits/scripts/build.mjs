#!/usr/bin/env node
/**
 * Compile rules/ into a single AGENTS.md, ordered by rules/_sections.md.
 * `--check` fails instead of writing when the committed file is stale.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { SKILL_DIR, readRules, readSections } from './lib.mjs'

const check = process.argv.includes('--check')
const OUT = join(SKILL_DIR, 'AGENTS.md')

const meta = JSON.parse(await readFile(join(SKILL_DIR, 'metadata.json'), 'utf8'))
const sections = await readSections()
const rules = await readRules()

const extra = async (f) => readFile(join(SKILL_DIR, f), 'utf8').catch(() => '')
const skillBody = (await extra('SKILL.md')).replace(/^---[\s\S]*?\n---\n/, '').trim()
const shellRef = (await extra('references/layout-shell.md')).trim()

const lines = [
  '<!-- Generated by scripts/build.mjs — do not edit by hand. -->',
  '',
  '# Wugweb Kits',
  '',
  `**Version ${meta.version}** · ${meta.organization} · ${meta.date}`,
  '',
  meta.abstract,
  '',
]

lines.push('## Skill body', '', skillBody, '', '---', '', '## Layout shell reference', '', shellRef, '', '---', '')
lines.push('## Contents', '')
for (const s of sections) {
  const rs = rules.filter((r) => r.section === s.id)
  lines.push(`${s.order}. **${s.title}** (${s.impact}) — ${rs.length} rules`)
  for (const r of rs) lines.push(`   - \`${r.id}\` — ${r.data.impactDescription ?? ''}`)
}
lines.push('')

for (const s of sections) {
  lines.push('---', '', `## ${s.order}. ${s.title}`, '', `**Impact:** ${s.impact}`, '', s.description, '')
  for (const r of rules.filter((x) => x.section === s.id)) {
    lines.push(
      `### \`${r.id}\``,
      '',
      `**Impact:** ${r.data.impact} — ${r.data.impactDescription ?? ''}`,
      '',
      r.body.replace(/^##\s+.*$/m, '').trim(),
      '',
    )
  }
}

if (meta.references?.length) {
  lines.push('---', '', '## References', '')
  for (const ref of meta.references) lines.push(`- ${ref}`)
  lines.push('')
}

const output = lines.join('\n')

if (check) {
  const current = await readFile(OUT, 'utf8').catch(() => null)
  if (current !== output) {
    console.error('AGENTS.md is stale. Run: node scripts/build.mjs')
    process.exit(1)
  }
  console.log('AGENTS.md is up to date.')
} else {
  await writeFile(OUT, output)
  console.log(`Wrote AGENTS.md — ${rules.length} rules, ${sections.length} sections.`)
}

#!/usr/bin/env node
// Render a made graphic from an HTML file to an image at an exact size
// (wugweb-work, Forms mode). Used for banners, share images, social cards,
// mockup compositions, diagrams and charts for decks and posts.
//
//   node scripts/render-graphic.mjs <file.html> --size 1200x630 [--out <file.png>]
//                                   [--scale 2] [--selector <css>] [--transparent]
//
// The HTML is the source of the graphic: text is real text, screens are the
// existing files linked by their media store addresses, colours and fonts come
// from the brand read. Nothing is generated by an image model. The picture is
// written under scripts/data/made/ (not committed). It reaches the site or a
// post only when the owner approves that one file and places it himself: this
// script uploads nothing and writes to no store.
//
// Each made file needs the owner's yes for that file before it is rendered.

import { chromium } from 'playwright';
import { mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname, basename } from 'node:path';
import { pathToFileURL } from 'node:url';

const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
const src = args.find((a) => /\.html?$/i.test(a));
const size = (opt('--size', '') || '').match(/^(\d+)x(\d+)$/);
if (!src || !size || !existsSync(src)) {
  console.error('Usage: node scripts/render-graphic.mjs <file.html> --size <width>x<height> [--out file.png] [--scale 2] [--selector css] [--transparent]');
  process.exit(2);
}
const [width, height] = [+size[1], +size[2]];
const out = resolve(opt('--out', `scripts/data/made/${basename(src).replace(/\.html?$/i, '')}-${width}x${height}.png`));
mkdirSync(dirname(out), { recursive: true });

const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width, height }, deviceScaleFactor: +opt('--scale', 2) });
  const failed = [];
  page.on('requestfailed', (r) => failed.push(r.url()));
  page.on('response', (r) => { if (r.status() >= 400) failed.push(`${r.status()} ${r.url()}`); });
  await page.goto(pathToFileURL(resolve(src)).href, { waitUntil: 'networkidle', timeout: 60000 });
  await page.evaluate(() => document.fonts.ready);
  const facts = await page.evaluate(({ width, height }) => {
    const broken = Array.from(document.images).filter((i) => i.complete && i.naturalWidth === 0).map((i) => i.src);
    const cropped = Array.from(document.images).filter((i) => {
      if (!i.naturalWidth) return false;
      const r = i.getBoundingClientRect(); const fit = getComputedStyle(i).objectFit;
      return (fit === 'cover' || fit === 'fill' || fit === 'none') && Math.abs(r.width / r.height - i.naturalWidth / i.naturalHeight) / (i.naturalWidth / i.naturalHeight) > 0.02;
    }).map((i) => i.src.split('/').pop());
    const overflow = document.documentElement.scrollWidth > width + 1 || document.documentElement.scrollHeight > height + 1;
    const small = Array.from(document.querySelectorAll('body *')).filter((el) => Array.from(el.childNodes).some((n) => n.nodeType === 3 && n.textContent.trim()) && parseFloat(getComputedStyle(el).fontSize) < 16).length;
    return { broken, cropped, overflow, small };
  }, { width, height });
  const problems = [];
  if (failed.length) problems.push(`could not load: ${failed.slice(0, 5).join(', ')}`);
  if (facts.broken.length) problems.push(`broken images: ${facts.broken.slice(0, 5).join(', ')}`);
  if (facts.cropped.length) problems.push(`cropped or reshaped: ${facts.cropped.join(', ')}`);
  if (facts.overflow) problems.push(`content runs past ${width}x${height}`);
  if (problems.length) {
    console.error(`Not rendered. ${problems.join('; ')}.`);
    process.exit(1);
  }
  const sel = opt('--selector', '');
  const shot = { path: out, omitBackground: args.includes('--transparent') };
  if (sel) await page.locator(sel).first().screenshot(shot); else await page.screenshot({ ...shot, clip: { x: 0, y: 0, width, height } });
  console.log(`Rendered ${out} at ${width}x${height} (x${opt('--scale', 2)}).${facts.small ? ` Flag: ${facts.small} text elements under 16 px.` : ''} Not uploaded anywhere.`);
} finally {
  await browser.close();
}
